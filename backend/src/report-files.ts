type ReportRow = Record<string, unknown>
type WorkbookInput = { title: string; generatedAt: string; generatedBy: string; periodStart: string; periodEnd: string; timezone?: string; granularity?: string; rows: ReportRow[]; estimatedCostIdr?: string | null; estimatedTco2e?: string | null; tariffIds?: string[]; factorIds?: string[]; factorSources?: string[]; factorUrls?: string[]; energySources?: string[] }
const reportColumnOrder = ['date', 'bucketStart', 'siteId', 'siteName', 'meterId', 'id', 'quality', 'kwh', 'energyKwh', 'unit', 'readingCount', 'resetCount', 'rolloverCount', 'title', 'status', 'severity', 'message', 'ruleName', 'triggeredAt', 'resolvedAt', 'assignedAuditorId', 'scheduledAt', 'findingCount']
export function reportColumns(rows: ReportRow[]) {
  const columns = [...new Set(rows.flatMap(row => Object.keys(row)))], priority = (key: string) => { const index = reportColumnOrder.indexOf(key); return index < 0 ? reportColumnOrder.length : index }
  return columns.sort((left, right) => priority(left) - priority(right) || left.localeCompare(right))
}

function xml(value: unknown) {
  return String(value ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&apos;')
}

const crcTable = Uint32Array.from({ length: 256 }, (_, n) => {
  let c = n
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
  return c >>> 0
})

function crc32(input: Buffer) {
  let value = 0xffffffff
  for (const byte of input) value = crcTable[(value ^ byte) & 0xff] ^ (value >>> 8)
  return (value ^ 0xffffffff) >>> 0
}

function zip(files: Array<{ name: string; contents: string }>) {
  const local: Buffer[] = [], central: Buffer[] = []
  let offset = 0
  for (const file of files) {
    const name = Buffer.from(file.name, 'utf8'), data = Buffer.from(file.contents, 'utf8'), checksum = crc32(data)
    const header = Buffer.alloc(30)
    header.writeUInt32LE(0x04034b50, 0); header.writeUInt16LE(20, 4); header.writeUInt32LE(0, 6); header.writeUInt16LE(0, 8)
    header.writeUInt32LE(checksum, 14); header.writeUInt32LE(data.length, 18); header.writeUInt32LE(data.length, 22); header.writeUInt16LE(name.length, 26)
    local.push(header, name, data)
    const directory = Buffer.alloc(46)
    directory.writeUInt32LE(0x02014b50, 0); directory.writeUInt16LE(20, 4); directory.writeUInt16LE(20, 6); directory.writeUInt16LE(0, 8); directory.writeUInt16LE(0, 10)
    directory.writeUInt32LE(checksum, 16); directory.writeUInt32LE(data.length, 20); directory.writeUInt32LE(data.length, 24); directory.writeUInt16LE(name.length, 28); directory.writeUInt32LE(offset, 42)
    central.push(directory, name)
    offset += header.length + name.length + data.length
  }
  const centralSize = central.reduce((sum, part) => sum + part.length, 0), end = Buffer.alloc(22)
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(files.length, 8); end.writeUInt16LE(files.length, 10); end.writeUInt32LE(centralSize, 12); end.writeUInt32LE(offset, 16)
  return Buffer.concat([...local, ...central, end])
}

function sheet(rows: unknown[][]) {
  const col = (index: number) => { let n = index + 1, out = ''; while (n) { const digit = (n - 1) % 26; out = String.fromCharCode(65 + digit) + out; n = Math.floor((n - 1) / 26) }; return out }
  const body = rows.map((row, ri) => `<row r="${ri + 1}">${row.map((value, ci) => typeof value === 'number' && Number.isFinite(value) ? `<c r="${col(ci)}${ri + 1}"><v>${value}</v></c>` : `<c r="${col(ci)}${ri + 1}" t="inlineStr"><is><t xml:space="preserve">${xml(value)}</t></is></c>`).join('')}</row>`).join('')
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>${body}</sheetData></worksheet>`
}

export function createXlsxReport(input: WorkbookInput) {
  const columns = reportColumns(input.rows)
  const rows: unknown[][] = [
    [input.title], ['Period start UTC', input.periodStart], ['Period end UTC', input.periodEnd], ['Report timezone', input.timezone ?? 'UTC'], ['Granularity', input.granularity ?? 'DAY'], ['Generated at UTC', input.generatedAt], ['Generated by', input.generatedBy],
    ['Estimated cost IDR', input.estimatedCostIdr ?? ''], ['Tariff version IDs', (input.tariffIds ?? []).join(';')], ['Estimated tCO2e', input.estimatedTco2e ?? ''], ['Emission factor IDs', (input.factorIds ?? []).join(';')], ['Emission energy sources', (input.energySources ?? []).join(';')], ['Emission sources', (input.factorSources ?? []).join(';')], ['Emission source URLs', (input.factorUrls ?? []).join(';')],
    [], columns, ...input.rows.map(row => columns.map(column => row[column] instanceof Date ? (row[column] as Date).toISOString() : row[column]))
  ]
  return zip([
    { name: '[Content_Types].xml', contents: '<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/></Types>' },
    { name: '_rels/.rels', contents: '<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>' },
    { name: 'xl/workbook.xml', contents: '<?xml version="1.0" encoding="UTF-8"?><workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets><sheet name="Energy" sheetId="1" r:id="rId1"/></sheets></workbook>' },
    { name: 'xl/_rels/workbook.xml.rels', contents: '<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/></Relationships>' },
    { name: 'xl/worksheets/sheet1.xml', contents: sheet(rows) }
  ])
}

function pdfText(value: unknown) { return String(value ?? '').replace(/[^\x20-\x7E]/g, '?').replace(/([\\()])/g, '\\$1') }

export function createPdfReport(input: WorkbookInput) {
  const columns = reportColumns(input.rows)
  const lines = [
    input.title, `Period start UTC: ${input.periodStart}`, `Period end UTC: ${input.periodEnd}`, `Report timezone: ${input.timezone ?? 'UTC'}`, `Granularity: ${input.granularity ?? 'DAY'}`, `Generated at UTC: ${input.generatedAt}`, `Generated by: ${input.generatedBy}`,
    `Estimated cost IDR: ${input.estimatedCostIdr ?? 'N/A'}`, `Tariff version IDs: ${(input.tariffIds ?? []).join(';') || 'N/A'}`, `Estimated tCO2e: ${input.estimatedTco2e ?? 'N/A'}`, `Emission factor IDs: ${(input.factorIds ?? []).join(';') || 'N/A'}`, `Emission energy sources: ${(input.energySources ?? []).join(';') || 'N/A'}`, `Emission sources: ${(input.factorSources ?? []).join(';') || 'N/A'}`, `Emission source URLs: ${(input.factorUrls ?? []).join(';') || 'N/A'}`, '', columns.join('       '), ...input.rows.map(row => columns.map(column => row[column] instanceof Date ? (row[column] as Date).toISOString() : row[column] ?? '').join('       '))
  ]
  const pageLines = Array.from({ length: Math.max(1, Math.ceil(lines.length / 45)) }, (_, index) => lines.slice(index * 45, (index + 1) * 45))
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    `<< /Type /Pages /Kids [${pageLines.map((_, index) => `${4 + index * 2} 0 R`).join(' ')}] /Count ${pageLines.length} >>`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>'
  ]
  pageLines.forEach((page, index) => {
    const pageId = 4 + index * 2, contentId = pageId + 1
    const commands = ['BT', '/F1 10 Tf', '50 790 Td', ...page.flatMap((line, lineIndex) => [lineIndex ? '0 -16 Td' : '', `(${pdfText(line)}) Tj`]).filter(Boolean), 'ET'].join('\n')
    const stream = Buffer.from(commands, 'ascii')
    objects.push(`<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 842] /Resources << /Font << /F1 3 0 R >> >> /Contents ${contentId} 0 R >>`)
    objects.push(`<< /Length ${stream.length} >>\nstream\n${stream.toString('ascii')}\nendstream`)
  })
  const parts: Buffer[] = [Buffer.from('%PDF-1.4\n%ET\n', 'ascii')], offsets = [0]
  let offset = parts[0].length
  objects.forEach((object, index) => { offsets.push(offset); const part = Buffer.from(`${index + 1} 0 obj\n${object}\nendobj\n`, 'ascii'); parts.push(part); offset += part.length })
  const xrefOffset = offset
  const xref = ['xref', `0 ${objects.length + 1}`, '0000000000 65535 f ', ...offsets.slice(1).map(value => `${String(value).padStart(10, '0')} 00000 n `), 'trailer', `<< /Size ${objects.length + 1} /Root 1 0 R >>`, 'startxref', String(xrefOffset), '%%EOF', ''].join('\n')
  parts.push(Buffer.from(xref, 'ascii'))
  return Buffer.concat(parts)
}
